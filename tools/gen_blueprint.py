#!/usr/bin/env python3
"""gen_blueprint.py (s63, ruling 2026-09-28 22:18) -- the Blueprint of the paper, generated, never hand-edited.

Usage: python3 tools/gen_blueprint.py <package_root> <out_dir>

One node per numbered statement environment of submission/native/sections (read through tools/proof_companion.py, the
same generator that writes release/PROOF_COMPANION.md), with
  - its trust label, derived only from shipped records:
      F    Lean declaration(s) registered in submission/native/PAPER_CLAIMS.tsv, no external hypothesis;
      F+H  registered, with the named external hypotheses the registry lists (TCER, the Grunewald-Segal code-uniform
           form, DPRM over N), which are hypotheses of the Lean theorem and never axioms;
      S    Lean name(s) listed in release/STATEMENT_MAP_FULL.md but not a registry row;
      M    proved in the paper; no Lean declaration is listed for it (for Lemma 10.8 this is the documented boundary);
      D / R  definition / remark or example (no trust claim);
  - the Lean names and frozen statement file, the source section file, and
  - "uses": the numbered statements its proof names (a textual reading of the proof; an edge means "is cited in the
    proof", not a checked dependency).
Writes BLUEPRINT.md, blueprint_nodes.tsv, dep_graph.dot.  The statements and proofs themselves are not copied: they
are in the paper and, per statement, in release/PROOF_COMPANION.md (anchors are the statement labels).
Deterministic: the same inputs give the same bytes (no dates, sorted where order is not document order)."""
import os, re, subprocess, sys, tempfile, csv
root, out = sys.argv[1], sys.argv[2]
os.makedirs(out, exist_ok=True)
tmp = tempfile.mkdtemp()
comp = os.path.join(tmp, "companion.md")
subprocess.run([sys.executable, os.path.join(root, "tools", "proof_companion.py"),
                os.path.join(root, "submission", "native"), comp], check=True, capture_output=True)
text = open(comp, encoding="utf-8").read()
KINDS = r"(Theorem|Lemma|Proposition|Corollary|Definition|Remark|Examples?)"
nodes = []
for block in re.split(r"(?m)^## ", text)[1:]:
    head, _, body = block.partition("\n")
    m = re.match(KINDS + r" ([0-9A-Z]+\.[0-9]+)\s*$", head.strip())
    if not m: continue
    kind, num = m.group(1), m.group(2)
    src = (re.search(r"- source: `([^`]+)`", body) or [None, ""])[1]
    proof = body.split("**Proof.**", 1)[1] if "**Proof.**" in body else ""
    uses = sorted({f"{k} {n}" for k, n in re.findall(KINDS + r"\s+([0-9A-Z]+\.[0-9]+)", proof)
                   if f"{k} {n}" != f"{kind} {num}"}, key=lambda s: [(0, int(x), "") if x.isdigit() else (1, 0, x) for x in re.split(r"[ .]", s)])
    nodes.append({"label": f"{kind} {num}", "kind": kind, "num": num, "src": src, "uses": uses, "has_proof": bool(proof.strip())})
reg = {}
with open(os.path.join(root, "submission", "native", "PAPER_CLAIMS.tsv"), encoding="utf-8") as f:
    for r in csv.DictReader(f, delimiter="\t"):
        reg[r["paper_label"].strip()] = (r["Lean_root"].strip(), r["external_hypotheses"].strip())
smap = {}
for line in open(os.path.join(root, "release", "STATEMENT_MAP_FULL.md"), encoding="utf-8"):
    c = [x.strip() for x in line.strip().strip("|").split("|")]
    if len(c) == 4 and re.match(r"[0-9A-Z]+\.[0-9]+$", c[0]):
        smap[c[0]] = (c[2], c[3])
for n in nodes:
    lean, ext = reg.get(n["label"], ("", ""))
    sm_lean, sm_file = smap.get(n["num"], ("—", "—"))
    n["lean"] = lean or (sm_lean if sm_lean != "—" else "")
    n["frozen"] = sm_file if sm_file != "—" else ""
    if n["kind"] == "Definition": lab = "D"
    elif n["kind"] in ("Remark", "Example", "Examples"): lab = "R"
    elif lean and (ext.lower().startswith("none") or not ext): lab = "F"
    elif lean: lab = "F+H"
    elif n["lean"]: lab = "S"
    else: lab = "M"
    n["trust"], n["ext"] = lab, ("" if ext.lower().startswith("none") else ext)
count = {}
for n in nodes: count[n["trust"]] = count.get(n["trust"], 0) + 1
with open(os.path.join(out, "blueprint_nodes.tsv"), "w", encoding="utf-8") as f:
    f.write("label\ttrust\tlean\texternal_hypotheses\tfrozen_file\tsource\tuses\n")
    for n in nodes:
        f.write("\t".join([n["label"], n["trust"], n["lean"], n["ext"], n["frozen"], n["src"], ", ".join(n["uses"])]) + "\n")
with open(os.path.join(out, "dep_graph.dot"), "w", encoding="utf-8") as f:
    f.write("digraph blueprint {\n  rankdir=LR; node [shape=box, fontsize=10];\n")
    style = {"F": "solid", "F+H": "dashed", "S": "solid", "M": "dotted", "D": "rounded", "R": "rounded"}
    for n in nodes:
        f.write(f'  "{n["label"]}" [style="{style[n["trust"]]}", label="{n["label"]}\\n{n["trust"]}"];\n')
    known = {n["label"] for n in nodes}
    for n in nodes:
        for u in n["uses"]:
            if u in known: f.write(f'  "{u}" -> "{n["label"]}";\n')
    f.write("}\n")
L = ["# Blueprint", "",
     "Generated by `tools/gen_blueprint.py` from `submission/native/sections/` (through `tools/proof_companion.py`),",
     "`submission/native/PAPER_CLAIMS.tsv` and `release/STATEMENT_MAP_FULL.md`; not maintained by hand. Every numbered",
     "statement of the paper is one node. The statement and its proof are in the paper and, entry by entry, in",
     "`release/PROOF_COMPANION.md`; this file adds what a reader checking the paper needs beside them: the trust label,",
     "the Lean names, the frozen statement file, and the statements each proof cites. `dep_graph.dot` draws the",
     "citation edges (render with `dot -Tpdf dep_graph.dot -o dep_graph.pdf`).", "",
     "## Trust labels", "",
     "| label | meaning | nodes |", "|---|---|---|",
     f"| F | a Lean declaration registered for the statement (`PAPER_CLAIMS.tsv`); standard axioms only; no external hypothesis | {count.get('F',0)} |",
     f"| F+H | registered Lean declaration whose statement carries named external hypotheses (listed in the node) — hypotheses, never axioms | {count.get('F+H',0)} |",
     f"| S | Lean name(s) listed in the statement map, not a registry row | {count.get('S',0)} |",
     f"| M | proved in the paper; no Lean declaration is listed | {count.get('M',0)} |",
     f"| D | definition | {count.get('D',0)} |",
     f"| R | remark or examples | {count.get('R',0)} |",
     "", f"Nodes: {len(nodes)}. Recorded elaborated types and axiom footprints for the registered paper declarations are in",
     "`certificates/PaperClaimTypeReport_current.log`. `certificates/FinalAxiomReport_current.log` is a separate",
     "report over its own listed roots, not the registry-wide report.", "",
     "## Nodes", "",
     "| node | trust | Lean | external hypotheses | frozen file | cited in its proof |", "|---|---|---|---|---|---|"]
def cell(s): return (s or "—").replace("|", "\\|")
for n in nodes:
    lean = ", ".join(f"`{x.strip().strip('`')}`" for x in n["lean"].split(",") if x.strip()) if n["lean"] else ""
    L.append(f"| {n['label']} | {n['trust']} | {cell(lean)} | {cell(n['ext'])} | {cell(n['frozen'])} | {cell(', '.join(n['uses']))} |")
open(os.path.join(out, "BLUEPRINT.md"), "w", encoding="utf-8").write("\n".join(L) + "\n")
print("BLUEPRINT nodes=%d %s" % (len(nodes), " ".join(f"{k}={count[k]}" for k in sorted(count))))
