#!/usr/bin/env python3
"""proof_companion.py -- the proof companion, generated ONE WAY from the native TeX (s38, Gate-12 C01).

For every statement environment of submission/native/sections/ (numbered or Part-numbered) it emits
the label, the head (Lean names cited), the statement text and the proof text that follows it,
as normalised plain text (native_statement_check.norm-style, but keeping spaces).  Nothing is
copied by hand: the build regenerates the file and refuses to ship if the shipped copy differs.

Usage: python3 tools/proof_companion.py <native_dir> <out.md>
Prints PROOF_COMPANION_STATEMENTS=<n> PROOF_COMPANION_WITH_PROOF=<n>
"""
import glob, os, re, sys, unicodedata
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from native_statement_check import ENV2KIND, _cref

def detex(s):
    s = re.sub(r"\\[cC]ref\{([a-z]+):([0-9A-Z.]+)\}", _cref, s)
    s = re.sub(r"\\eqref\{eq:([0-9A-Z.]+)\}", r"(\1)", s)
    s = re.sub(r"\\cite\{([^}]*)\}", r"[\1]", s)
    s = re.sub(r"\\allowbreak\{\}", "", s)
    s = re.sub(r"\\texttt\{([^{}]*)\}", r"`\1`", s)
    s = re.sub(r"\\(?:emph|textit)\{([^{}]*)\}", r"*\1*", s)
    s = re.sub(r"\\textbf\{([^{}]*)\}", r"**\1**", s)
    s = re.sub(r"\\(?:text|tag|tilde|label)(?:\[[^\]]*\])?\{([^{}]*)\}", r"\1", s)
    s = re.sub(r"\\begin\{(itemize|enumerate|gathered|equation)\}|\\end\{(itemize|enumerate|gathered|equation)\}", "", s)
    s = s.replace("\\item ", "- ").replace("\\[", "").replace("\\]", "").replace("\\quad", "  ").replace("\\\\", "")
    s = re.sub(r"\\_", "_", s)
    s = re.sub(r"\\([{}%&#])", r"\1", s)
    s = re.sub(r"\\[A-Za-z]+\*?", "", s)
    s = s.replace("$", "")
    s = re.sub(r"[ \t]+", " ", s)
    return s.strip()

def main():
    native, out = sys.argv[1], sys.argv[2]
    rows = []
    for f in sorted(glob.glob(os.path.join(native, "sections", "*.tex"))):
        t = open(f, encoding="utf-8").read()
        pat = re.compile(r"\\begin\{(theorem|lemma|proposition|corollary|definition|remark|example|conjecture|notation|question)(Part|\*)?\}(?:\[(.*?)\])?(?:\\label(?:\[[^\]]*\])?\{([^}]*)\})?(.*?)\\end\{\1\2?\}", re.S)
        for m in pat.finditer(t):
            env, note, lab, body = m.group(1), m.group(3) or "", m.group(4) or "", m.group(5)
            after = t[m.end():]
            gap = re.match(r"(?:\s|%[^\n]*\n)*", after).group(0)
            proof = ""
            mp = re.match(r"\\begin\{proof\}(?:\[[^\]]*\])?(.*?)\\end\{proof\}", after[len(gap):], re.S)
            if mp: proof = mp.group(1)
            rows.append((os.path.basename(f), ENV2KIND[env], lab, detex(note), detex(body), detex(proof)))
    with open(out, "w", encoding="utf-8") as w:
        w.write("# Proof companion\n\nGenerated by `tools/proof_companion.py` from `submission/native/sections/` at build time; not maintained by hand. One entry per statement environment, in document order, with the proof environment that directly follows it (empty when the proof is grouped or pointed to elsewhere).\n\n")
        for f, kind, lab, note, body, proof in rows:
            w.write("## %s %s\n\n" % (kind, lab.split(":")[-1] if lab else "(unnumbered)"))
            w.write("- source: `%s`%s\n" % (f, ("  \n- head: " + note) if note else ""))
            w.write("\n**Statement.** %s\n\n" % body)
            if proof: w.write("**Proof.** %s\n\n" % proof)
    print("PROOF_COMPANION_STATEMENTS=%d PROOF_COMPANION_WITH_PROOF=%d" % (len(rows), sum(1 for r in rows if r[5])))

if __name__ == "__main__":
    main()
