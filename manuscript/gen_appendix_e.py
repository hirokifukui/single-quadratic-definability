#!/usr/bin/env python3
"""gen_appendix_e.py — regenerate Appendix E (statement map) from frozen_statements/.
The frozen file IS the signature of record; this script never reads the production tree.
Usage: python3 manuscript/gen_appendix_e.py frozen_statements manuscript/APPENDIX_E_STATEMENT_MAP.md"""
import re, sys, glob, os, io
base, out = sys.argv[1], sys.argv[2]
rows = []
for f in sorted(glob.glob(os.path.join(base, "*_STATEMENTS.lean"))):
    s = io.open(f, encoding='utf-8').read()
    for m in re.finditer(r'^(theorem|def|noncomputable def) (\S+)((?:.|\n)*?):=', s, re.M):
        kind, name, sig = m.group(1), m.group(2), m.group(3)
        sig = re.sub(r'\s+', ' ', sig).strip()
        sig = sig.replace('|', '\\|')
        rows.append((name, kind, os.path.basename(f), sig))
w = io.open(out, 'w', encoding='utf-8')
w.write("# Appendix E — Statement map (generated from frozen_statements/, signature of record)\n\n")
w.write("Generated by `manuscript/gen_appendix_e.py`; do not edit by hand. %d entries.\n\n" % len(rows))
w.write("| Lean name | frozen file | signature |\n|---|---|---|\n")
for name, kind, f, sig in rows:
    w.write("| `%s` (%s) | %s | `%s` |\n" % (name, kind, f, sig))
w.close()
print("APPENDIX_E entries=%d -> %s" % (len(rows), out))
